#!/bin/bash
# EG-DESK Project References Setup
# Clones/pulls references from GitHub based on project-refs.txt and ~/.claude/reference-registry.tsv.
# Generates references/manifest.tsv for WM/LLM consumption.
#
# project-refs.txt format:
#   Flat:    name
#   Grouped: group-name/
#              name1
#              name2

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REF_DIR="$SCRIPT_DIR/references"
REGISTRY="$HOME/.claude/reference-registry.tsv"
PROJECT_REFS_FILE="$REF_DIR/project-refs.txt"
MANIFEST="$REF_DIR/manifest.tsv"
NOTES_DIR="$HOME/.claude/reference-notes"
CLAUDE_DIR="$HOME/.claude"
MAX_CLONE_SIZE_KB=512000  # 500MB in KB

# ─── Repo Size Check ───
# Returns 0 (ok to clone) or 1 (too large). Uses GitHub API.

check_repo_size() {
    local url=$1
    local name=$2
    # Extract owner/repo from URL (https://github.com/owner/repo.git)
    local owner_repo=$(echo "$url" | sed -E 's|https://github.com/||; s|\.git$||')
    if [ -z "$owner_repo" ]; then return 0; fi

    local size_kb=$(curl -sf "https://api.github.com/repos/$owner_repo" 2>/dev/null | grep '"size":' | head -1 | sed 's/[^0-9]//g')
    if [ -z "$size_kb" ]; then return 0; fi  # API fail → allow clone

    if [ "$size_kb" -gt "$MAX_CLONE_SIZE_KB" ] && [ "$FULL_CLONE" = false ]; then
        local size_mb=$((size_kb / 1024))
        echo "   ⚠  $name is ${size_mb}MB (>${MAX_CLONE_SIZE_KB}KB) — skipping (use --full to force)"
        return 1
    fi
    return 0
}

# ─── Registry Lookup ───

lookup_registry() {
    local ref_name=$1
    if [ ! -f "$REGISTRY" ]; then
        echo ""
        return
    fi
    while IFS= read -r raw_line; do
        [[ "$raw_line" =~ ^#.*$ ]] && continue
        [ -z "$raw_line" ] && continue
        # Split by tab — use awk to handle empty first field correctly
        local url name type tags desc
        url=$(echo "$raw_line" | awk -F'\t' '{print $1}')
        name=$(echo "$raw_line" | awk -F'\t' '{print $2}')
        type=$(echo "$raw_line" | awk -F'\t' '{print $3}')
        tags=$(echo "$raw_line" | awk -F'\t' '{print $4}')
        desc=$(echo "$raw_line" | awk -F'\t' '{print $5}')
        [ -z "$name" ] && continue
        if [ "$name" = "$ref_name" ]; then
            echo "$url|$name|$type|$tags|$desc"
            return
        fi
    done < "$REGISTRY"
    echo ""
}

# ─── Read project-refs.txt ───
# Output format: rel_path|registry_name
#   Flat:    "theia|theia"
#   Grouped: "browser-automation/playwright|playwright"

read_project_refs() {
    if [ ! -f "$PROJECT_REFS_FILE" ]; then
        echo "   ❌ $PROJECT_REFS_FILE not found" >&2
        exit 1
    fi
    # Group stack — supports up to 3 levels of nesting
    local group_0="" group_1="" group_2=""

    while IFS= read -r line; do
        [[ "$line" =~ ^#.*$ || -z "$line" ]] && continue

        # Count leading spaces → depth (2 spaces per level)
        local stripped="${line#"${line%%[! ]*}"}"
        local indent=$((${#line} - ${#stripped}))
        local depth=$((indent / 2))
        local trimmed=$(echo "$stripped" | xargs)
        [ -z "$trimmed" ] && continue

        # Group header (ends with /)
        if [[ "$trimmed" =~ /$ ]]; then
            local gname="${trimmed%/}"
            case $depth in
                0) group_0="$gname"; group_1=""; group_2="" ;;
                1) group_1="$gname"; group_2="" ;;
                2) group_2="$gname" ;;
            esac
            continue
        fi

        # Flat ref at depth 0 — reset all groups
        if [ $depth -eq 0 ]; then
            group_0=""; group_1=""; group_2=""
            echo "${trimmed}|${trimmed}"
            continue
        fi

        # Leaf at depth > 0 — build path from group stack
        local path=""
        [ -n "$group_0" ] && [ $depth -ge 1 ] && path="${group_0}/"
        [ -n "$group_1" ] && [ $depth -ge 2 ] && path="${path}${group_1}/"
        [ -n "$group_2" ] && [ $depth -ge 3 ] && path="${path}${group_2}/"
        echo "${path}${trimmed}|${trimmed}"
    done < "$PROJECT_REFS_FILE"
}

# ─── Generate manifest.tsv ───

generate_manifest() {
    echo "# Auto-generated by setup.sh — do not edit manually" > "$MANIFEST"
    echo "# Source: ~/.claude/reference-registry.tsv" >> "$MANIFEST"
    echo "# Format: name<TAB>path<TAB>type<TAB>tags<TAB>description<TAB>status<TAB>has_note" >> "$MANIFEST"

    while IFS='|' read -r rel_path ref_name; do
        local entry=$(lookup_registry "$ref_name")
        if [ -z "$entry" ]; then continue; fi
        IFS='|' read -r url name type tags desc <<< "$entry"

        # Determine status
        local status="not-cloned"
        if [ "$type" = "git" ] && [ -d "$REF_DIR/$rel_path/.git" ]; then
            status="cloned"
        elif [ "$type" = "docs" ] && [ -d "$REF_DIR/$rel_path" ]; then
            status="present"
        fi

        # Check for note
        local has_note="no"
        if [ -f "$NOTES_DIR/$ref_name.md" ]; then
            has_note="yes"
        fi

        printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n" "$ref_name" "$rel_path" "$type" "$tags" "$desc" "$status" "$has_note" >> "$MANIFEST"
    done < <(read_project_refs)
}

# ─── Sync ~/.claude registry ───

sync_claude_registry() {
    if [ -d "$CLAUDE_DIR/.git" ]; then
        echo "   📡 Syncing ~/.claude registry..."
        (cd "$CLAUDE_DIR" && git pull --rebase 2>/dev/null) || echo "   ⚠  ~/.claude git pull failed (offline?)"
    fi
}

push_claude_registry() {
    if [ -d "$CLAUDE_DIR/.git" ]; then
        (cd "$CLAUDE_DIR" && git add reference-registry.tsv && \
         git commit -m "registry: $1" 2>/dev/null && \
         git pull --rebase 2>/dev/null && \
         git push 2>/dev/null) || echo "   ⚠  ~/.claude git push failed — changes saved locally"
    fi
}

# ─── Health Check ───

check_health() {
    echo ""
    echo "📋 Reference Health Check"
    echo "========================="

    local healthy=0
    local missing=0

    while IFS='|' read -r rel_path ref_name; do
        local entry=$(lookup_registry "$ref_name")
        if [ -z "$entry" ]; then
            echo "   ⚠  $ref_name — not in registry"
            continue
        fi
        IFS='|' read -r url name type tags desc <<< "$entry"

        if [ "$type" = "git" ]; then
            if [ -d "$REF_DIR/$rel_path/.git" ]; then
                echo "   ✅ $rel_path (git)"
                ((healthy++))
            elif [ -n "$url" ] && ! check_repo_size "$url" "$ref_name" 2>/dev/null; then
                echo "   📦 $rel_path (registry only, too large)"
                ((healthy++))
            else
                echo "   ⬜ $rel_path (not cloned)"
                ((missing++))
            fi
        elif [ "$type" = "docs" ]; then
            if [ -d "$REF_DIR/$rel_path" ]; then
                echo "   📁 $rel_path (docs)"
                ((healthy++))
            else
                echo "   ⬜ $rel_path (docs, missing)"
                ((missing++))
            fi
        fi
    done < <(read_project_refs)

    echo ""
    echo "   Healthy: $healthy | Missing: $missing"
}

# ─── Orphan Check ───

check_orphans() {
    local expected_paths=()
    while IFS='|' read -r rel_path _name; do
        expected_paths+=("$rel_path")
    done < <(read_project_refs)

    # Check all git repos at any depth
    while IFS= read -r gitdir; do
        local repo_dir=$(dirname "$gitdir")
        local rel="${repo_dir#$REF_DIR/}"
        local found=false
        for expected in "${expected_paths[@]}"; do
            [ "$expected" = "$rel" ] && found=true && break
        done
        if [ "$found" = false ]; then
            echo "   ⚠  references/$rel/ is not in project-refs.txt"
            echo "      Remove: rm -rf \"references/$rel\""
            echo "      Keep:   Add to references/project-refs.txt"
        fi
    done < <(find "$REF_DIR" -name ".git" -type d 2>/dev/null)

    # Check top-level non-git dirs that aren't group containers
    for dir in "$REF_DIR"/*/; do
        [ -d "$dir" ] || continue
        local dname=$(basename "$dir")
        [ "$dname" = "." ] && continue
        [ -d "$dir/.git" ] && continue  # already checked above

        # Skip if this is a group container (any expected path starts with dname/)
        local is_group=false
        for expected in "${expected_paths[@]}"; do
            [[ "$expected" == "$dname/"* ]] && is_group=true && break
        done
        [ "$is_group" = true ] && continue

        # Not a git repo and not a group — orphan docs folder
        local found=false
        for expected in "${expected_paths[@]}"; do
            [ "$expected" = "$dname" ] && found=true && break
        done
        if [ "$found" = false ]; then
            echo "   ⚠  references/$dname/ is not in project-refs.txt"
            echo "      Remove: rm -rf \"references/$dname\""
        fi
    done
}

# ─── Parse arguments ───

ACTION=""
ADD_NAME=""
ADD_URL=""
ADD_TAGS=""
ADD_DESC=""
EDIT_NAME=""
REMOVE_NAME=""
FULL_CLONE=false

while [[ $# -gt 0 ]]; do
    case $1 in
        --full)    FULL_CLONE=true; shift ;;
        --update)  ACTION="update"; shift ;;
        --check)   ACTION="check"; shift ;;
        --add-global) ACTION="add-global"; ADD_NAME="$2"; ADD_URL="$3"; shift 3
                   while [[ $# -gt 0 ]]; do
                       case $1 in
                           --tags) ADD_TAGS="$2"; shift 2 ;;
                           --desc) ADD_DESC="$2"; shift 2 ;;
                           *) shift ;;
                       esac
                   done ;;
        --add)     ACTION="add"; ADD_NAME="$2"; ADD_URL="$3"; shift 3
                   while [[ $# -gt 0 ]]; do
                       case $1 in
                           --tags) ADD_TAGS="$2"; shift 2 ;;
                           --desc) ADD_DESC="$2"; shift 2 ;;
                           *) shift ;;
                       esac
                   done ;;
        --edit)    ACTION="edit"; EDIT_NAME="$2"; shift 2
                   while [[ $# -gt 0 ]]; do
                       case $1 in
                           --tags) ADD_TAGS="$2"; shift 2 ;;
                           --desc) ADD_DESC="$2"; shift 2 ;;
                           *) shift ;;
                       esac
                   done ;;
        --remove)  ACTION="remove"; REMOVE_NAME="$2"; shift 2 ;;
        --help|-h)
            echo "Usage: ./setup.sh [options]"
            echo ""
            echo "Options:"
            echo "  (no args)      Clone/pull references + generate manifest (skip >500MB)"
            echo "  --full         Clone all references regardless of size"
            echo "  --update       Git pull all cloned references"
            echo "  --check        Show reference health status"
            echo "  --add <name> <url> --tags <t> --desc <d>   Add a reference (clone + project + registry)"
            echo "  --add-global <name> <url> --tags <t> --desc <d>   Registry only (no clone, no project)"
            echo "  --edit <name> --tags <t> --desc <d>        Edit registry metadata (global)"
            echo "  --remove <name>   Remove from this project (registry unchanged)"
            echo ""
            echo "project-refs.txt format:"
            echo "  name              Flat reference (clone to references/name/)"
            echo "  group-name/       Group folder header"
            echo "    name1           Group member (clone to references/group-name/name1/)"
            echo "    name2"
            exit 0 ;;
        *) shift ;;
    esac
done

# ─── Actions ───

if [ "$ACTION" = "check" ]; then
    check_health
    check_orphans
    exit 0
fi

if [ "$ACTION" = "update" ]; then
    echo "🔄 Updating references..."
    sync_claude_registry
    while IFS='|' read -r rel_path ref_name; do
        local_entry=$(lookup_registry "$ref_name")
        [ -z "$local_entry" ] && continue
        IFS='|' read -r url name type tags desc <<< "$local_entry"
        if [ "$type" = "git" ] && [ -d "$REF_DIR/$rel_path/.git" ]; then
            echo "   📥 $rel_path..."
            (cd "$REF_DIR/$rel_path" && git pull 2>/dev/null) || echo "   ⚠  $rel_path pull failed"
        fi
    done < <(read_project_refs)
    generate_manifest
    check_health
    exit 0
fi

if [ "$ACTION" = "add-global" ]; then
    if [ -z "$ADD_NAME" ] || [ -z "$ADD_URL" ]; then
        echo "❌ Usage: ./setup.sh --add-global <name> <url> --tags <tags> --desc <description>"
        exit 1
    fi
    echo "🌐 Adding $ADD_NAME to global registry only..."

    # Upsert registry
    if ! grep -q "	${ADD_NAME}	" "$REGISTRY" 2>/dev/null; then
        printf "%s\t%s\tgit\t%s\t%s\n" "$ADD_URL" "$ADD_NAME" "$ADD_TAGS" "$ADD_DESC" >> "$REGISTRY"
    else
        echo "   ℹ  $ADD_NAME already in registry"
    fi

    push_claude_registry "add-global $ADD_NAME"
    echo "   ✅ $ADD_NAME added to registry (not cloned, not in this project)"
    exit 0
fi

if [ "$ACTION" = "add" ]; then
    if [ -z "$ADD_NAME" ] || [ -z "$ADD_URL" ]; then
        echo "❌ Usage: ./setup.sh --add <name> <url> --tags <tags> --desc <description>"
        exit 1
    fi
    echo "➕ Adding $ADD_NAME..."

    # Clone (with size check)
    if [ ! -d "$REF_DIR/$ADD_NAME" ]; then
        if check_repo_size "$ADD_URL" "$ADD_NAME"; then
            git clone --depth 1 "$ADD_URL" "$REF_DIR/$ADD_NAME" || { echo "❌ Clone failed"; exit 1; }
        fi
    fi

    # Add to project-refs.txt (check both flat and grouped)
    if ! read_project_refs 2>/dev/null | grep -q "|${ADD_NAME}$"; then
        echo "$ADD_NAME" >> "$PROJECT_REFS_FILE"
    else
        echo "   ℹ  $ADD_NAME already in project-refs.txt"
    fi

    # Upsert registry
    if ! grep -q "	${ADD_NAME}	" "$REGISTRY" 2>/dev/null; then
        printf "%s\t%s\tgit\t%s\t%s\n" "$ADD_URL" "$ADD_NAME" "$ADD_TAGS" "$ADD_DESC" >> "$REGISTRY"
    fi

    push_claude_registry "add $ADD_NAME"
    generate_manifest
    echo "   ✅ $ADD_NAME added"
    exit 0
fi

if [ "$ACTION" = "edit" ]; then
    if [ -z "$EDIT_NAME" ]; then
        echo "❌ Usage: ./setup.sh --edit <name> --tags <tags> --desc <description>"
        exit 1
    fi
    echo "✏️  Editing $EDIT_NAME in global registry..."

    # Build new line
    local_entry=$(lookup_registry "$EDIT_NAME")
    if [ -z "$local_entry" ]; then
        echo "❌ $EDIT_NAME not found in registry"
        exit 1
    fi
    IFS='|' read -r old_url old_name old_type old_tags old_desc <<< "$local_entry"
    new_tags="${ADD_TAGS:-$old_tags}"
    new_desc="${ADD_DESC:-$old_desc}"

    # Replace line in registry (match by name column)
    tmp_file=$(mktemp)
    while IFS= read -r raw_line || [ -n "$raw_line" ]; do
        # Pass through comments and blank lines verbatim
        if [[ "$raw_line" =~ ^#.*$ ]] || [ -z "$raw_line" ]; then
            echo "$raw_line" >> "$tmp_file"
            continue
        fi
        IFS=$'\t' read -r url name type tags desc <<< "$raw_line"
        if [ "$name" = "$EDIT_NAME" ]; then
            printf "%s\t%s\t%s\t%s\t%s\n" "$old_url" "$old_name" "$old_type" "$new_tags" "$new_desc" >> "$tmp_file"
        else
            echo "$raw_line" >> "$tmp_file"
        fi
    done < "$REGISTRY"
    mv "$tmp_file" "$REGISTRY"

    push_claude_registry "edit $EDIT_NAME"
    generate_manifest
    echo "   ✅ $EDIT_NAME updated"
    exit 0
fi

if [ "$ACTION" = "remove" ]; then
    if [ -z "$REMOVE_NAME" ]; then
        echo "❌ Usage: ./setup.sh --remove <name>"
        exit 1
    fi
    echo "➖ Removing $REMOVE_NAME from this project..."

    # Find rel_path for this name
    local remove_path=""
    while IFS='|' read -r rel_path ref_name; do
        if [ "$ref_name" = "$REMOVE_NAME" ]; then
            remove_path="$rel_path"
            break
        fi
    done < <(read_project_refs)

    # Remove from project-refs.txt (match trimmed name)
    if [ -f "$PROJECT_REFS_FILE" ]; then
        tmp_file=$(mktemp)
        while IFS= read -r line; do
            local trimmed=$(echo "$line" | xargs)
            if [ "$trimmed" = "$REMOVE_NAME" ]; then
                continue
            fi
            echo "$line" >> "$tmp_file"
        done < "$PROJECT_REFS_FILE"
        mv "$tmp_file" "$PROJECT_REFS_FILE"
    fi

    # Remove folder (use rel_path if found, fallback to name)
    local target="${remove_path:-$REMOVE_NAME}"
    if [ -d "$REF_DIR/$target" ]; then
        rm -rf "$REF_DIR/$target"
        echo "   🗑  references/$target/ deleted"
    fi

    # Clean up empty group folder if this was a grouped ref
    if [[ "$target" == */* ]]; then
        local group_dir="$REF_DIR/$(dirname "$target")"
        if [ -d "$group_dir" ] && [ -z "$(ls -A "$group_dir" 2>/dev/null)" ]; then
            rmdir "$group_dir"
            local group_name=$(dirname "$target")
            echo "   🗑  references/$group_name/ (empty group) deleted"
            # Remove empty group header from project-refs.txt
            if [ -f "$PROJECT_REFS_FILE" ]; then
                tmp_file=$(mktemp)
                while IFS= read -r line; do
                    local trimmed=$(echo "$line" | xargs)
                    if [ "$trimmed" = "${group_name}/" ]; then
                        continue
                    fi
                    echo "$line" >> "$tmp_file"
                done < "$PROJECT_REFS_FILE"
                mv "$tmp_file" "$PROJECT_REFS_FILE"
            fi
        fi
    fi

    generate_manifest
    echo "   ✅ $REMOVE_NAME removed (registry unchanged)"
    exit 0
fi

# ─── Default: Clone/Pull + Manifest ───

echo "📦 Setting up EG-DESK references..."
echo ""

sync_claude_registry

while IFS='|' read -r rel_path ref_name; do
    local_entry=$(lookup_registry "$ref_name")
    if [ -z "$local_entry" ]; then
        echo "   ⚠  $ref_name — not in registry, skipping"
        continue
    fi
    IFS='|' read -r url name type tags desc <<< "$local_entry"

    if [ "$type" = "git" ]; then
        if [ -d "$REF_DIR/$rel_path/.git" ]; then
            echo "   ✅ $rel_path (exists)"
        elif [ "$rel_path" != "$ref_name" ] && [ -d "$REF_DIR/$ref_name/.git" ]; then
            # Flat clone exists but grouped path expected → migrate
            echo "   📦 $ref_name → $rel_path (migrating)..."
            mkdir -p "$(dirname "$REF_DIR/$rel_path")"
            mv "$REF_DIR/$ref_name" "$REF_DIR/$rel_path"
        elif [ -n "$url" ]; then
            if check_repo_size "$url" "$ref_name"; then
                echo "   📥 $rel_path (cloning)..."
                mkdir -p "$(dirname "$REF_DIR/$rel_path")"
                git clone --depth 1 "$url" "$REF_DIR/$rel_path" 2>/dev/null || echo "   ❌ $rel_path clone failed"
            fi
        fi
    elif [ "$type" = "docs" ]; then
        if [ -d "$REF_DIR/$rel_path" ]; then
            echo "   📁 $rel_path (docs, exists)"
        elif [ "$rel_path" != "$ref_name" ] && [ -d "$REF_DIR/$ref_name" ]; then
            # Flat docs folder exists but grouped path expected → migrate
            echo "   📦 $ref_name → $rel_path (migrating)..."
            mkdir -p "$(dirname "$REF_DIR/$rel_path")"
            mv "$REF_DIR/$ref_name" "$REF_DIR/$rel_path"
        else
            mkdir -p "$REF_DIR/$rel_path"
            echo "   📁 $rel_path (docs, created — add files manually)"
        fi
    fi
done < <(read_project_refs)

generate_manifest
check_health
check_orphans
