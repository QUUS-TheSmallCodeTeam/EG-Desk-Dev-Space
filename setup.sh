#!/bin/bash
# EG-DESK Project References Setup
# Clones/pulls references from GitHub based on project-refs.txt and ~/.claude/reference-registry.tsv.
# Generates references/manifest.tsv for WM/LLM consumption.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REF_DIR="$SCRIPT_DIR/references"
REGISTRY="$HOME/.claude/reference-registry.tsv"
PROJECT_REFS_FILE="$REF_DIR/project-refs.txt"
MANIFEST="$REF_DIR/manifest.tsv"
NOTES_DIR="$HOME/.claude/reference-notes"
CLAUDE_DIR="$HOME/.claude"

# ─── Registry Lookup ───

lookup_registry() {
    local ref_name=$1
    if [ ! -f "$REGISTRY" ]; then
        echo ""
        return
    fi
    while IFS= read -r raw_line; do
        [[ "$raw_line" =~ ^#.*$ ]] && continue
        [ -z "$raw_line" ] && continue
        # Split by tab — use awk to handle empty first field correctly
        local url name type tags desc
        url=$(echo "$raw_line" | awk -F'\t' '{print $1}')
        name=$(echo "$raw_line" | awk -F'\t' '{print $2}')
        type=$(echo "$raw_line" | awk -F'\t' '{print $3}')
        tags=$(echo "$raw_line" | awk -F'\t' '{print $4}')
        desc=$(echo "$raw_line" | awk -F'\t' '{print $5}')
        [ -z "$name" ] && continue
        if [ "$name" = "$ref_name" ]; then
            echo "$url|$name|$type|$tags|$desc"
            return
        fi
    done < "$REGISTRY"
    echo ""
}

# ─── Read project-refs.txt ───
# Usage: while IFS= read -r ref_name; do ... done < <(read_project_refs)

read_project_refs() {
    if [ ! -f "$PROJECT_REFS_FILE" ]; then
        echo "   ❌ $PROJECT_REFS_FILE not found" >&2
        exit 1
    fi
    while IFS= read -r line; do
        [[ "$line" =~ ^#.*$ || -z "$line" ]] && continue
        line=$(echo "$line" | xargs)  # trim whitespace
        [ -n "$line" ] && echo "$line"
    done < "$PROJECT_REFS_FILE"
}

# ─── Generate manifest.tsv ───

generate_manifest() {
    echo "# Auto-generated by setup.sh — do not edit manually" > "$MANIFEST"
    echo "# Source: ~/.claude/reference-registry.tsv" >> "$MANIFEST"
    echo "# Format: name<TAB>type<TAB>tags<TAB>description<TAB>status<TAB>has_note" >> "$MANIFEST"

    while IFS= read -r ref_name; do
        local entry=$(lookup_registry "$ref_name")
        if [ -z "$entry" ]; then continue; fi
        IFS='|' read -r url name type tags desc <<< "$entry"

        # Determine status
        local status="not-cloned"
        if [ "$type" = "git" ] && [ -d "$REF_DIR/$name/.git" ]; then
            status="cloned"
        elif [ "$type" = "docs" ] && [ -d "$REF_DIR/$name" ]; then
            status="present"
        fi

        # Check for note
        local has_note="no"
        if [ -f "$NOTES_DIR/$name.md" ]; then
            has_note="yes"
        fi

        printf "%s\t%s\t%s\t%s\t%s\t%s\n" "$name" "$type" "$tags" "$desc" "$status" "$has_note" >> "$MANIFEST"
    done < <(read_project_refs)
}

# ─── Sync ~/.claude registry ───

sync_claude_registry() {
    if [ -d "$CLAUDE_DIR/.git" ]; then
        echo "   📡 Syncing ~/.claude registry..."
        (cd "$CLAUDE_DIR" && git pull --rebase 2>/dev/null) || echo "   ⚠  ~/.claude git pull failed (offline?)"
    fi
}

push_claude_registry() {
    if [ -d "$CLAUDE_DIR/.git" ]; then
        (cd "$CLAUDE_DIR" && git add reference-registry.tsv && \
         git commit -m "registry: $1" 2>/dev/null && \
         git pull --rebase 2>/dev/null && \
         git push 2>/dev/null) || echo "   ⚠  ~/.claude git push failed — changes saved locally"
    fi
}

# ─── Health Check ───

check_health() {
    echo ""
    echo "📋 Reference Health Check"
    echo "========================="

    local healthy=0
    local missing=0

    while IFS= read -r ref_name; do
        local entry=$(lookup_registry "$ref_name")
        if [ -z "$entry" ]; then
            echo "   ⚠  $ref_name — not in registry"
            continue
        fi
        IFS='|' read -r url name type tags desc <<< "$entry"

        if [ "$type" = "git" ]; then
            if [ -d "$REF_DIR/$name/.git" ]; then
                echo "   ✅ $name (git)"
                ((healthy++))
            else
                echo "   ⬜ $name (not cloned)"
                ((missing++))
            fi
        elif [ "$type" = "docs" ]; then
            if [ -d "$REF_DIR/$name" ]; then
                echo "   📁 $name (docs)"
                ((healthy++))
            else
                echo "   ⬜ $name (docs, missing)"
                ((missing++))
            fi
        fi
    done < <(read_project_refs)

    echo ""
    echo "   Healthy: $healthy | Missing: $missing"
}

# ─── Orphan Check ───

check_orphans() {
    local project_refs=()
    while IFS= read -r r; do project_refs+=("$r"); done < <(read_project_refs)
    for dir in "$REF_DIR"/*/; do
        [ -d "$dir" ] || continue
        local dname=$(basename "$dir")
        [ "$dname" = "." ] && continue

        local found=false
        for ref in "${project_refs[@]}"; do
            [ "$ref" = "$dname" ] && found=true && break
        done

        if [ "$found" = false ]; then
            echo "   ⚠  references/$dname/ is not in project-refs.txt"
            echo "      Remove: ./setup.sh --remove $dname"
            echo "      Keep:   Add '$dname' to references/project-refs.txt"
        fi
    done
}

# ─── Parse arguments ───

ACTION=""
ADD_NAME=""
ADD_URL=""
ADD_TAGS=""
ADD_DESC=""
EDIT_NAME=""
REMOVE_NAME=""

while [[ $# -gt 0 ]]; do
    case $1 in
        --update)  ACTION="update"; shift ;;
        --check)   ACTION="check"; shift ;;
        --add)     ACTION="add"; ADD_NAME="$2"; ADD_URL="$3"; shift 3
                   while [[ $# -gt 0 ]]; do
                       case $1 in
                           --tags) ADD_TAGS="$2"; shift 2 ;;
                           --desc) ADD_DESC="$2"; shift 2 ;;
                           *) shift ;;
                       esac
                   done ;;
        --edit)    ACTION="edit"; EDIT_NAME="$2"; shift 2
                   while [[ $# -gt 0 ]]; do
                       case $1 in
                           --tags) ADD_TAGS="$2"; shift 2 ;;
                           --desc) ADD_DESC="$2"; shift 2 ;;
                           *) shift ;;
                       esac
                   done ;;
        --remove)  ACTION="remove"; REMOVE_NAME="$2"; shift 2 ;;
        --help|-h)
            echo "Usage: ./setup.sh [options]"
            echo ""
            echo "Options:"
            echo "  (no args)      Clone/pull references + generate manifest"
            echo "  --update       Git pull all cloned references"
            echo "  --check        Show reference health status"
            echo "  --add <name> <url> --tags <t> --desc <d>   Add a reference"
            echo "  --edit <name> --tags <t> --desc <d>        Edit registry metadata (global)"
            echo "  --remove <name>   Remove from this project (registry unchanged)"
            exit 0 ;;
        *) shift ;;
    esac
done

# ─── Actions ───

if [ "$ACTION" = "check" ]; then
    check_health
    check_orphans
    exit 0
fi

if [ "$ACTION" = "update" ]; then
    echo "🔄 Updating references..."
    sync_claude_registry
    while IFS= read -r ref_name; do
        local_entry=$(lookup_registry "$ref_name")
        [ -z "$local_entry" ] && continue
        IFS='|' read -r url name type tags desc <<< "$local_entry"
        if [ "$type" = "git" ] && [ -d "$REF_DIR/$name/.git" ]; then
            echo "   📥 $name..."
            (cd "$REF_DIR/$name" && git pull 2>/dev/null) || echo "   ⚠  $name pull failed"
        fi
    done < <(read_project_refs)
    generate_manifest
    check_health
    exit 0
fi

if [ "$ACTION" = "add" ]; then
    if [ -z "$ADD_NAME" ] || [ -z "$ADD_URL" ]; then
        echo "❌ Usage: ./setup.sh --add <name> <url> --tags <tags> --desc <description>"
        exit 1
    fi
    echo "➕ Adding $ADD_NAME..."

    # Clone
    if [ ! -d "$REF_DIR/$ADD_NAME" ]; then
        git clone --depth 1 "$ADD_URL" "$REF_DIR/$ADD_NAME" || { echo "❌ Clone failed"; exit 1; }
    fi

    # Add to project-refs.txt
    if ! grep -qx "$ADD_NAME" "$PROJECT_REFS_FILE" 2>/dev/null; then
        echo "$ADD_NAME" >> "$PROJECT_REFS_FILE"
    fi

    # Upsert registry
    if ! grep -q "	${ADD_NAME}	" "$REGISTRY" 2>/dev/null; then
        printf "%s\t%s\tgit\t%s\t%s\n" "$ADD_URL" "$ADD_NAME" "$ADD_TAGS" "$ADD_DESC" >> "$REGISTRY"
    fi

    push_claude_registry "add $ADD_NAME"
    generate_manifest
    echo "   ✅ $ADD_NAME added"
    exit 0
fi

if [ "$ACTION" = "edit" ]; then
    if [ -z "$EDIT_NAME" ]; then
        echo "❌ Usage: ./setup.sh --edit <name> --tags <tags> --desc <description>"
        exit 1
    fi
    echo "✏️  Editing $EDIT_NAME in global registry..."

    # Build new line
    local_entry=$(lookup_registry "$EDIT_NAME")
    if [ -z "$local_entry" ]; then
        echo "❌ $EDIT_NAME not found in registry"
        exit 1
    fi
    IFS='|' read -r old_url old_name old_type old_tags old_desc <<< "$local_entry"
    new_tags="${ADD_TAGS:-$old_tags}"
    new_desc="${ADD_DESC:-$old_desc}"

    # Replace line in registry (match by name column)
    tmp_file=$(mktemp)
    while IFS= read -r raw_line || [ -n "$raw_line" ]; do
        # Pass through comments and blank lines verbatim
        if [[ "$raw_line" =~ ^#.*$ ]] || [ -z "$raw_line" ]; then
            echo "$raw_line" >> "$tmp_file"
            continue
        fi
        IFS=$'\t' read -r url name type tags desc <<< "$raw_line"
        if [ "$name" = "$EDIT_NAME" ]; then
            printf "%s\t%s\t%s\t%s\t%s\n" "$old_url" "$old_name" "$old_type" "$new_tags" "$new_desc" >> "$tmp_file"
        else
            echo "$raw_line" >> "$tmp_file"
        fi
    done < "$REGISTRY"
    mv "$tmp_file" "$REGISTRY"

    push_claude_registry "edit $EDIT_NAME"
    generate_manifest
    echo "   ✅ $EDIT_NAME updated"
    exit 0
fi

if [ "$ACTION" = "remove" ]; then
    if [ -z "$REMOVE_NAME" ]; then
        echo "❌ Usage: ./setup.sh --remove <name>"
        exit 1
    fi
    echo "➖ Removing $REMOVE_NAME from this project..."

    # Remove from project-refs.txt
    if [ -f "$PROJECT_REFS_FILE" ]; then
        grep -vx "$REMOVE_NAME" "$PROJECT_REFS_FILE" > "$PROJECT_REFS_FILE.tmp" || true
        mv "$PROJECT_REFS_FILE.tmp" "$PROJECT_REFS_FILE"
    fi

    # Remove folder
    if [ -d "$REF_DIR/$REMOVE_NAME" ]; then
        rm -rf "$REF_DIR/$REMOVE_NAME"
        echo "   🗑  references/$REMOVE_NAME/ deleted"
    fi

    generate_manifest
    echo "   ✅ $REMOVE_NAME removed (registry unchanged)"
    exit 0
fi

# ─── Default: Clone/Pull + Manifest ───

echo "📦 Setting up EG-DESK references..."
echo ""

sync_claude_registry

while IFS= read -r ref_name; do
    local_entry=$(lookup_registry "$ref_name")
    if [ -z "$local_entry" ]; then
        echo "   ⚠  $ref_name — not in registry, skipping"
        continue
    fi
    IFS='|' read -r url name type tags desc <<< "$local_entry"

    if [ "$type" = "git" ]; then
        if [ -d "$REF_DIR/$name/.git" ]; then
            echo "   ✅ $name (exists)"
        elif [ -n "$url" ]; then
            echo "   📥 $name (cloning)..."
            git clone --depth 1 "$url" "$REF_DIR/$name" 2>/dev/null || echo "   ❌ $name clone failed"
        fi
    elif [ "$type" = "docs" ]; then
        if [ -d "$REF_DIR/$name" ]; then
            echo "   📁 $name (docs, exists)"
        else
            mkdir -p "$REF_DIR/$name"
            echo "   📁 $name (docs, created — add files manually)"
        fi
    fi
done < <(read_project_refs)

generate_manifest
check_health
check_orphans
