import { realpath, stat } from 'node:fs/promises'
import path from 'node:path'
import { publicEpochMs } from './codex-account-usage.mjs'

export const MAX_TEXT = 20000

// Shell-like argument tokens, including quoted/escaped values. This is a
// redaction aid, not a shell parser or a guarantee of detecting every secret.
const argumentValue = String.raw`(?:(?:"(?:\\.|[^"\\])*(?:"|$)|'[^']*(?:'|$)|\\[\s\S]|[^\s;&|"']+)+)`
const credentialArgument = new RegExp(String.raw`(^|[\s(])((?:--(?:password|passwd|pwd|password-file|token|access[-_]token|refresh[-_]token|session[-_]token|bearer[-_]token|private[-_]token|api[-_]?key|secret|client[-_]secret|secret[-_]access[-_]key|access[-_]key(?:[-_]id)?|authorization|auth|user|proxy-user|cookie)|-[uUp])(?:\s*=\s*|\s+))${argumentValue}`, 'gi')
const attachedCredentialArgument = new RegExp(String.raw`(^|[\s(])(-[uUp])(${argumentValue})`, 'g')
const masked = (match, prefix = '', label = '[REDACTED]') => prefix + label + (match.slice(prefix.length).match(/\r\n|\r|\n/g) || []).join('')

// No raw tool arguments/results, diffs, environment or reasoning enter public state.
// Text that is intentionally public still gets common credential patterns redacted.
export function publicText(value, limit = MAX_TEXT) {
  if (typeof value !== 'string') return ''
  return value
    .replace(credentialArgument, (match, lead, flag) => masked(match, lead + flag))
    .replace(attachedCredentialArgument, (match, lead, flag) => masked(match, lead + flag))
    .replace(/(?<![a-z0-9+.-])([a-z][a-z0-9+.-]*:\/\/)[^\s/@]+:[^\s/@]+@/gi, '$1[REDACTED]@')
    .replace(/(\b(?:proxy-)?authorization\s*[:=]\s*)Digest\s+[^"'\r\n]*/gi, (match, prefix) => masked(match, prefix))
    .replace(/(\b(?:proxy-)?authorization\s*[:=]\s*)(?:(?:basic|bearer|token|negotiate)\s+)?(?:"[^"\n]*"|'[^'\n]*'|[^\s"']+)/gi, (match, prefix) => masked(match, prefix))
    .replace(/(\b(?:set-cookie|cookie)\s*:\s*)[^"'\r\n]*/gi, '$1[REDACTED]')
    .replace(/-----BEGIN [^-]*PRIVATE KEY-----[\s\S]*?(?:-----END [^-]*PRIVATE KEY-----|$)/g, match => masked(match, '', '[REDACTED PRIVATE KEY]'))
    .replace(/\b(?:sk-[A-Za-z0-9_-]+|gh[pousr]_[A-Za-z0-9_]+|github_pat_[A-Za-z0-9_]+|xox[baprs]-[A-Za-z0-9-]+)\b/g, '[REDACTED]')
    .replace(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\b/g, '[REDACTED]')
    .replace(/\b(Bearer\s+)\S+/gi, '$1[REDACTED]')
    .replace(/(?<![\w-])((?:["']?[\w-]*(?:password|passwd|secret|api[_-]?key|token|cookie|authorization)[\w-]*["']?)\s*[:=]\s*)(?:"[^"\n]*"|'[^'\n]*'|[^\s,;}]+)/gi, '$1[REDACTED]')
    .replace(/([?&](?:token|key|code|secret|access_token|api_key)=)[^&#\s]+/gi, '$1[REDACTED]')
    .slice(0, limit)
}

export function publicNetworkContext(value) {
  if (!value || typeof value !== 'object') return null
  const { host, protocol } = value
  if (typeof host !== 'string' || host.length > 260 || !/^(?:[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?(?::\d{1,5})?|\[[0-9a-f:]+\](?::\d{1,5})?)$/i.test(host)) return null
  // Values generated by CLI 0.156.1's NetworkApprovalProtocol schema.
  if (!['http', 'https', 'socks5Tcp', 'socks5Udp'].includes(protocol)) return null
  return { host, protocol }
}

export const ERROR_KINDS = ['auth', 'quota', 'permission', 'network', 'model', 'unknown']

// CodexErrorInfo string variants of the codex 0.162.1 app-server schema
// (ErrorNotification/TurnCompleted TurnError) by recovery: auth = sign in again,
// quota = wait for reset or another account, permission = policy/sandbox/
// approval block, network = retry the connection, model = change the request
// or start a new conversation. 'other' carries no cause and falls through.
const CODEX_ERROR_KINDS = new Map([
  ['unauthorized', 'auth'],
  ['usageLimitExceeded', 'quota'], ['rateLimitExceeded', 'quota'],
  ['cyberPolicy', 'permission'], ['misalignmentPolicyViolation', 'permission'], ['tooManyDenials', 'permission'], ['sandboxError', 'permission'],
  ['serverOverloaded', 'network'], ['internalServerError', 'network'],
  ['contextWindowExceeded', 'model'], ['sessionBudgetExceeded', 'model'], ['flexUnavailable', 'model'], ['badRequest', 'model'],
  ['threadRollbackFailed', 'unknown'],
])
// Object variants carrying an optional upstream httpStatusCode.
const CODEX_TRANSPORT_ERRORS = ['httpConnectionFailed', 'responseStreamConnectionFailed', 'responseStreamDisconnected', 'responseTooManyFailedAttempts']
const HTTP_STATUS_KINDS = new Map([[401, 'auth'], [403, 'permission'], [429, 'quota']])
// Bridge-issued codes whose cause is unambiguous; other codes stay unknown.
const BRIDGE_CODE_KINDS = new Map([['LOGIN_REQUIRED', 'auth'], ['CONNECTION_LOST', 'network'], ['BRIDGE_OFFLINE', 'network'], ['RPC_TIMEOUT', 'network']])
// Last resort for messages without a structured cause (e.g. JSON-RPC rejects).
const MESSAGE_KINDS = [
  ['quota', /\b(?:usage limit|rate limit|quota exceeded)\b/i],
  ['auth', /\b(?:unauthori[sz]ed|not (?:logged|signed) in|(?:log|sign) in again|re-?authenticate|token (?:has )?expired)\b/i],
  ['permission', /\b(?:permission denied|forbidden|access denied|not permitted)\b/i],
  ['network', /\b(?:ECONNREFUSED|ECONNRESET|ENOTFOUND|ETIMEDOUT|EAI_AGAIN|network error|stream disconnected|connection (?:refused|reset|closed|lost)|is not connected)\b/i],
]

function codexInfoKind(info) {
  if (typeof info === 'string') return CODEX_ERROR_KINDS.get(info) || null
  if (!info || typeof info !== 'object' || Array.isArray(info)) return null
  if (Object.hasOwn(info, 'activeTurnNotSteerable')) return 'unknown'
  const variant = CODEX_TRANSPORT_ERRORS.find(name => Object.hasOwn(info, name))
  if (!variant) return null
  return HTTP_STATUS_KINDS.get(info[variant]?.httpStatusCode) || 'network'
}

export function publicErrorKind(error, code) {
  const fromInfo = error && typeof error === 'object' ? codexInfoKind(error.codexErrorInfo) : null
  if (fromInfo) return fromInfo
  const fromCode = BRIDGE_CODE_KINDS.get(String(code)) || (typeof error?.code === 'string' ? BRIDGE_CODE_KINDS.get(error.code) : null)
  if (fromCode) return fromCode
  const message = typeof error === 'string' ? error : typeof error?.message === 'string' ? error.message : ''
  return MESSAGE_KINDS.find(([, pattern]) => pattern.test(message.slice(0, 2000)))?.[0] || 'unknown'
}

// code/origin/message are unchanged; kind is added, and retryAt (quota reset,
// epoch ms) only when the caller or a bridge error supplies one.
export function publicError(error, code = 'CHAT_ERROR', origin = 'bridge', { retryAt } = {}) {
  const result = { code: String(code), origin, message: publicText(error?.message || error || 'Codex request failed', 2000), kind: publicErrorKind(error, code) }
  // Only bridge-made Error objects may carry retryAt; native payloads cannot.
  const resetAt = publicEpochMs(retryAt ?? (error instanceof Error ? error.retryAt : undefined))
  if (resetAt !== null) result.retryAt = resetAt
  return result
}

export function chatError(code, message, httpStatus = 400) {
  return Object.assign(new Error(message), { code, httpStatus })
}

export function validateChatCwd(body) {
  if (body.cwd === undefined) return undefined
  if (typeof body.cwd !== 'string' || !path.isAbsolute(body.cwd) || body.cwd.includes('\0')) {
    throw chatError('INVALID_CWD', 'cwd must be an absolute local path')
  }
  return body.cwd
}

const artifactExtensions = new Set(['.pdf', '.docx', '.xlsx', '.xls', '.pptx', '.csv', '.tsv', '.txt', '.md', '.png', '.jpg', '.jpeg', '.webp', '.gif'])
const scriptExtensions = /\.(?:[cm]?js|jsx|tsx?|sh|bash|zsh|fish|py|rb|pl|php|ps1|bat|cmd|exe|app|html?|svg|wasm)$/i
const sensitivePath = /(?:^|[/\\])(?:\.env(?:\.[^/\\]*)?|\.ssh|\.aws|\.gnupg|auth\.json|credentials(?:\.json)?|id_rsa|id_ed25519)(?:$|[/\\])|\.(?:pem|key|p12|pfx)$/i

export async function verifyLocalFile(candidate, { artifact = false } = {}) {
  if (typeof candidate !== 'string' || !path.isAbsolute(candidate) || /[\u0000-\u001f]/.test(candidate)) return null
  if (candidate.startsWith('//') || sensitivePath.test(candidate)) return null
  if (artifact && (!artifactExtensions.has(path.extname(candidate).toLowerCase()) || scriptExtensions.test(candidate))) return null
  try {
    const canonical = await realpath(candidate)
    if (sensitivePath.test(canonical)) return null
    if (artifact && (!artifactExtensions.has(path.extname(canonical).toLowerCase()) || scriptExtensions.test(canonical))) return null
    const info = await stat(canonical)
    if (!info.isFile() || (artifact && (info.mode & 0o111))) return null
    return canonical
  } catch { return null }
}

// Only explicit Markdown file links. Ordinary text, URLs, labels and commands
// are never evidence of a file write, nor are they converted into documents.
export function explicitFileLinks(text) {
  const links = []
  for (const match of String(text || '').matchAll(/\[([^\]\n]{1,160})\]\((?:<([^>\n]+)>|(\/[^)\n]+))\)/g)) {
    const raw = (match[2] || match[3] || '').replace(/:\d+(?::\d+)?$/, '')
    if (path.isAbsolute(raw) && !raw.startsWith('//')) links.push({ label: publicText(match[1], 160), path: raw })
    if (links.length === 20) break
  }
  return links
}
