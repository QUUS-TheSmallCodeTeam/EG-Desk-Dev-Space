#!/usr/bin/env bash
set -euo pipefail

PROFILE="${EGDESK_FIREFOX_PROFILE:-$HOME/Library/Application Support/Firefox/Profiles/egtc3irr.egdesk.default-release}"
FIREFOX="${EGDESK_FIREFOX_BIN:-$HOME/Applications/Firefox.app/Contents/MacOS/firefox}"
LAUNCH_MODE="${EGDESK_FIREFOX_MODE:-automation}"
MARIONETTE_PORT="${EGDESK_FIREFOX_MARIONETTE_PORT-2828}"
REMOTE_AGENT_PORT="${EGDESK_FIREFOX_REMOTE_AGENT_PORT-6000}"
validate_port() {
  local value="$1" name="$2"
  if [[ ! "$value" =~ ^[1-9][0-9]{0,4}$ ]] || (( value > 65535 )); then
    echo "[ERROR] $name must be an integer from 1 to 65535" >&2
    exit 1
  fi
}
validate_port "$MARIONETTE_PORT" EGDESK_FIREFOX_MARIONETTE_PORT
validate_port "$REMOTE_AGENT_PORT" EGDESK_FIREFOX_REMOTE_AGENT_PORT
if [[ "$MARIONETTE_PORT" == "$REMOTE_AGENT_PORT" ]]; then
  echo "[ERROR] Firefox automation ports must differ" >&2
  exit 1
fi
case "${1:-}" in
  --normal) LAUNCH_MODE=normal; shift ;;
  --automation) LAUNCH_MODE=automation; shift ;;
esac
case "$LAUNCH_MODE" in
  normal|automation) ;;
  *) echo "[ERROR] EGDESK_FIREFOX_MODE must be normal or automation" >&2; exit 1 ;;
esac
START_URL="${1:-about:blank}"

if [[ ! -x "$FIREFOX" ]]; then
  echo "[ERROR] Firefox binary not found: $FIREFOX" >&2
  exit 1
fi

if [[ ! -d "$PROFILE" ]]; then
  echo "[ERROR] Firefox profile not found: $PROFILE" >&2
  exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
# Validate before the writer, overlay copy, or startup-cache cleanup can touch
# any profile. The writer repeats this check for direct invocations.
PROFILE="$(node "$SCRIPT_DIR/validate-firefox-profile.mjs" "$PROFILE")"
# Refuse an old, unbound or differently bound existing bridge before any
# profile/overlay write. This is read-only and never stops another process.
node "$REPO_ROOT/helper/egdesk-ontology-http.mjs" --check-existing-bridge "$PROFILE" > /dev/null
# Bind the validated profile and preserve its existing ontology graph before
# installing overlay resources. Failure stops before that graph can be copied over.
node "$REPO_ROOT/helper/egdesk-ontology-http.mjs" --prepare-profile "$PROFILE"
EGDESK_FIREFOX_PROFILE="$PROFILE" EGDESK_FIREFOX_MODE="$LAUNCH_MODE" \
EGDESK_FIREFOX_MARIONETTE_PORT="$MARIONETTE_PORT" \
EGDESK_FIREFOX_REMOTE_AGENT_PORT="$REMOTE_AGENT_PORT" \
  "$SCRIPT_DIR/write-userjs.sh"

# Both modes install the same current overlay into the already-validated
# dedicated profile. Normal mode still disables Marionette/remote debugging
# below; installing the UI must not require an automation launch.
mkdir -p "$PROFILE/chrome/JS" "$PROFILE/chrome/CSS" "$PROFILE/chrome/resources"
cp "$REPO_ROOT"/overlay/JS/*.uc.js "$PROFILE/chrome/JS/"
cp "$REPO_ROOT"/overlay/CSS/*.uc.css "$PROFILE/chrome/CSS/"
cp -R "$REPO_ROOT"/overlay/resources/. "$PROFILE/chrome/resources/"

# RT-05: the helper build this overlay expects (chrome://userchrome/content/
# egdesk-bridge-build.json), so a bridge left running on older source is
# detected. A failure only warns; a stale marker is removed, never kept.
BUILD_MARKER="$PROFILE/chrome/resources/egdesk-bridge-build.json"
if BUILD_HASH="$(node "$REPO_ROOT/helper/egdesk-bridge-build.mjs" 2>/dev/null)" && [[ "$BUILD_HASH" =~ ^[a-f0-9]{64}$ ]] \
  && BUILD_TMP="$(mktemp "$PROFILE/chrome/resources/.egdesk-bridge-build.XXXXXX" 2>/dev/null)"; then
  if ! { printf '{"buildHash":"%s"}\n' "$BUILD_HASH" > "$BUILD_TMP" && mv -f "$BUILD_TMP" "$BUILD_MARKER"; }; then
    rm -f "$BUILD_TMP" "$BUILD_MARKER" 2>/dev/null || true
    echo "[warn] could not write the expected bridge build marker; stale-bridge detection is off for this launch" >&2
  fi
else
  rm -f "$BUILD_MARKER" 2>/dev/null || true
  echo "[warn] bridge build hash unavailable; stale-bridge detection is off for this launch" >&2
fi

{
  echo "/* Auto-generated by EG-Desk MCP target launcher */"
  for css_file in "$PROFILE"/chrome/CSS/*.uc.css; do
    echo "@import url(\"CSS/$(basename "$css_file")\");"
  done
} > "$PROFILE/chrome/userChrome.css"

rm -rf "$PROFILE/startupCache"

# codex-bridge(:39218 — 터미널 PTY + codex chat/auth 백엔드) 미기동 시 자동 기동.
# 브리지가 없으면 overlay의 터미널 카드와 채팅 로그인이 전부 "오프라인"이 된다.
BRIDGE_STATE="$(node "$REPO_ROOT/helper/egdesk-ontology-http.mjs" --check-existing-bridge "$PROFILE")"
if [[ "$BRIDGE_STATE" == absent ]]; then
  BRIDGE_LOG="${TMPDIR:-/tmp}/egdesk-codex-bridge.log"
  echo "[info] codex-bridge not running — starting in background (log: $BRIDGE_LOG)"
  EGDESK_FIREFOX_PROFILE="$PROFILE" nohup "$SCRIPT_DIR/run-codex-bridge.sh" >> "$BRIDGE_LOG" 2>&1 &
elif [[ "$BRIDGE_STATE" == compatible ]]; then
  echo "[info] codex-bridge already running on :39218"
else
  echo "[ERROR] Existing bridge status could not be verified; no process was stopped" >&2
  exit 1
fi

echo "[info] Firefox: $FIREFOX"
echo "[info] Profile: $PROFILE"
echo "[info] Mode: $LAUNCH_MODE"
echo "[info] Start URL: $START_URL"

if [[ "$LAUNCH_MODE" == normal ]]; then
  echo "[info] Browser automation disabled; current overlay installed and session data retained"
  exec env -u MOZ_REMOTE_ALLOW_SYSTEM_ACCESS -u MOZ_MARIONETTE \
    "$FIREFOX" -profile "$PROFILE" --no-remote "$START_URL"
fi

echo "[info] Marionette: 127.0.0.1:$MARIONETTE_PORT"
echo "[info] Remote Agent: 127.0.0.1:$REMOTE_AGENT_PORT"
MOZ_REMOTE_ALLOW_SYSTEM_ACCESS=1 \
  "$FIREFOX" \
  -profile "$PROFILE" \
  --no-remote \
  --marionette \
  --remote-debugging-port "$REMOTE_AGENT_PORT" \
  --remote-allow-hosts localhost \
  "$START_URL"
